"use client";

import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { LoaderCircle, RefreshCw } from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { AI_USAGE_UPDATED_EVENT } from '@/lib/ai/limits';
import { generateSalesInsight, getSavedSalesInsight } from '@/lib/ai/actions';
import type { SalesInsightData } from '@/sales/types/ai';

export const useAIInsight = (data: SalesInsightData, enabled = true, initialInsight?: string | null) => {
  const dataKey = useMemo(() => JSON.stringify(data), [data]);
  const initialText = typeof initialInsight === 'string' && initialInsight.trim()
    ? initialInsight
    : null;
  const [insight, setInsight] = useState<{ key: string; text: string } | null>(() =>
    initialText ? { key: dataKey, text: initialText } : null
  );
  const [error, setError] = useState<{ key: string; message: string } | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [isCheckingDailyInsight, setIsCheckingDailyInsight] = useState(false);
  const hasAutoGenerated = useRef(Boolean(initialText));

  const handleGenerateInsight = useCallback(async (refresh = false) => {
    const requestKey = dataKey;
    setIsLoading(true);
    setError(null);

    let updateUsage = true;
    try {
      const result = await generateSalesInsight(data, refresh);
      updateUsage = !result.cached;
      if (result.text) {
        setInsight({ key: requestKey, text: result.text });
      } else {
        setError({ key: requestKey, message: result.error || 'Could not generate an insight. Please try again.' });
      }
    } catch {
      setError({ key: requestKey, message: 'Could not generate an insight. Please try again.' });
    } finally {
      if (updateUsage) window.dispatchEvent(new Event(AI_USAGE_UPDATED_EVENT));
      setIsLoading(false);
    }
  }, [data, dataKey]);

  const loadDailyInsight = useCallback(async () => {
    const requestKey = dataKey;
    setIsCheckingDailyInsight(true);
    setError(null);

    try {
      const saved = await getSavedSalesInsight();
      if (saved.text) {
        setInsight({ key: requestKey, text: saved.text });
        return;
      }
      if (saved.error) {
        setError({ key: requestKey, message: saved.error });
        return;
      }

      setIsCheckingDailyInsight(false);
      await handleGenerateInsight(false);
    } catch {
      setError({ key: requestKey, message: 'Could not load the saved AI insight. Please try again.' });
    } finally {
      setIsCheckingDailyInsight(false);
    }
  }, [dataKey, handleGenerateInsight]);

  useEffect(() => {
    if (enabled && data.totalOrders > 0 && !hasAutoGenerated.current) {
      hasAutoGenerated.current = true;
      void loadDailyInsight();
    }
  }, [data.totalOrders, enabled, loadDailyInsight]);

  const currentInsight = insight?.key === dataKey ? insight.text : null;
  const currentError = error?.key === dataKey ? error.message : null;
  const isCheckingForSavedInsight = isCheckingDailyInsight || (
    enabled && data.totalOrders > 0 && !hasAutoGenerated.current && !currentInsight && !currentError
  );

  return {
    insight: currentInsight,
    error: currentError,
    isLoading,
    isCheckingDailyInsight: isCheckingForSavedInsight,
    handleGenerateInsight,
  };
};

interface AIInsightButtonProps {
  isLoading: boolean;
  disabled?: boolean;
  onClick: () => void;
}

export const AIInsightButton = ({ isLoading, disabled = false, onClick }: AIInsightButtonProps) => (
  <button
    type="button"
    onClick={onClick}
    disabled={isLoading || disabled}
    aria-label={isLoading ? 'Generating insight' : 'Refresh insight'}
    className="inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-semibold bg-neutral-100 dark:bg-neutral-800 hover:bg-neutral-200 dark:hover:bg-neutral-700 text-neutral-700 dark:text-neutral-300 shadow-2xs transition-all disabled:cursor-not-allowed disabled:opacity-60"
  >
    {isLoading ? <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> : <RefreshCw className="h-3.5 w-3.5" />}
    <span className="hidden sm:inline">{isLoading ? 'Generating…' : 'Refresh'}</span>
  </button>
);

interface AIInsightWidgetProps {
  insight: string | null;
  error: string | null;
  isLoading: boolean;
  isCheckingDailyInsight: boolean;
}

export const AIInsightWidget = ({ insight, error, isLoading, isCheckingDailyInsight }: AIInsightWidgetProps) => (
  <div className="flex h-full min-h-26.5 flex-col gap-4">
    {error ? (
      <p role="alert" className="text-sm leading-6 text-rose-600 dark:text-rose-400">
        {error}
      </p>
    ) : insight ? (
      <div className="prose prose-sm dark:prose-invert max-w-none text-neutral-700 dark:text-neutral-200 [&_p]:my-1 [&_ul]:my-1 [&_ol]:my-1 [&_li]:my-0.5">
        <ReactMarkdown remarkPlugins={[remarkGfm]}>{insight}</ReactMarkdown>
      </div>
    ) : isCheckingDailyInsight ? null : (
      <p role={isLoading ? 'status' : undefined} className="text-sm leading-6 text-neutral-500 dark:text-neutral-400">
        {isLoading
          ? 'Generating a summary of the current sales…'
          : 'Select Refresh in the header to generate an insight.'}
      </p>
    )}
  </div>
);
